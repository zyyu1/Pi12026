/**
 * @page versuch07 Versuch07
 * @brief Overview of the extensions implemented for Versuch07.
 *
 * This exercise extends the student management program from Versuch06.
 *
 * Implemented features:
 * - comparison operators `<`, `>` and `==` in class Student
 * - output of Student objects via `std::ostream`
 * - stream operator `operator<<` for direct output with `std::cout`
 * - sorting the student list with `std::sort`
 * - deleting a student with `std::find`
 *
 * The comparison operators use the matriculation number as the ordering key.
 */
